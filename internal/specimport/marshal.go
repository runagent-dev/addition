package specimport

import (
	"bytes"

	"gopkg.in/yaml.v3"

	"github.com/runagent-dev/addition/internal/catalog"
)

const banner = "# Generated by tools/specgen from the API description named in `source`. Do not edit by hand.\n"

// Marshal renders set as the YAML file the catalog loads.
func Marshal(set *catalog.OperationSet) ([]byte, error) {
	var buf bytes.Buffer
	buf.WriteString(banner)
	enc := yaml.NewEncoder(&buf)
	enc.SetIndent(2)
	if err := enc.Encode(set); err != nil {
		return nil, err
	}
	if err := enc.Close(); err != nil {
		return nil, err
	}
	return buf.Bytes(), nil
}
